#!/usr/bin/env python3
"""Generate docs/assets/logo.svg: the terminal mark plus the "rustual" wordmark as outlines.

The wordmark is converted to paths (JetBrains Mono Bold, SIL OFL) so it renders identically
everywhere, and the canvas is fitted to the artwork so the logo is centered.

    uv run --with fonttools python scripts/make_logo.py [path/to/JetBrainsMono-Bold.ttf]
"""

from __future__ import annotations

import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT = "/usr/share/fonts/TTF/JetBrainsMonoNLNerdFontMono-Bold.ttf"
WORD = "rustual"
FONT_SIZE = 76
TRACKING = -2  # letter spacing in px
MARK = 112  # size of the terminal mark (square-ish: 112 x 104)
GAP = 24  # between mark and wordmark
PAD = 14  # outer margin on every side


def wordmark(font_path: str) -> tuple[str, tuple[float, float, float, float]]:
    """SVG path data for WORD at FONT_SIZE (baseline at y=0) and its bounds."""
    font = TTFont(font_path)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = FONT_SIZE / font["head"].unitsPerEm
    pen = SVGPathPen(glyphs)
    bounds = BoundsPen(glyphs)
    x = 0.0
    for ch in WORD:
        name = cmap[ord(ch)]
        # Font units are y-up; SVG is y-down.
        transform = (scale, 0, 0, -scale, x, 0)
        glyphs[name].draw(TransformPen(pen, transform))
        glyphs[name].draw(TransformPen(bounds, transform))
        x += glyphs[name].width * scale + TRACKING
    assert bounds.bounds is not None
    return pen.getCommands(), bounds.bounds


def main() -> None:
    font_path = sys.argv[1] if len(sys.argv) > 1 else FONT
    path, (x0, y0, x1, y1) = wordmark(font_path)
    word_w, word_h = x1 - x0, y1 - y0
    mark_w, mark_h = MARK, 104
    height = max(mark_h, word_h) + 2 * PAD
    width = PAD + mark_w + GAP + word_w + PAD
    # Vertically center both parts.
    mark_y = (height - mark_h) / 2
    word_dx = PAD + mark_w + GAP - x0
    word_dy = (height - word_h) / 2 - y0
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0f}" height="{height:.0f}" viewBox="0 0 {width:.2f} {height:.2f}" role="img" aria-label="rustual">
  <title>rustual</title>
  <!-- Generated by scripts/make_logo.py. Wordmark: JetBrains Mono Bold outlines (SIL OFL 1.1). -->
  <defs>
    <linearGradient id="mark" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#F74C00"/>
      <stop offset="0.55" stop-color="#E0457B"/>
      <stop offset="1" stop-color="#8B5CF6"/>
    </linearGradient>
    <linearGradient id="word" gradientUnits="userSpaceOnUse" x1="{x0:.2f}" y1="0" x2="{x1:.2f}" y2="0">
      <stop offset="0" stop-color="#F74C00"/>
      <stop offset="1" stop-color="#8B5CF6"/>
    </linearGradient>
  </defs>
  <g transform="translate({PAD} {mark_y:.2f})">
    <rect x="0" y="0" width="112" height="104" rx="18" fill="url(#mark)"/>
    <rect x="7" y="25" width="98" height="72" rx="11" fill="#14141A"/>
    <circle cx="20" cy="13" r="4.5" fill="#fff" fill-opacity="0.9"/>
    <circle cx="34" cy="13" r="4.5" fill="#fff" fill-opacity="0.6"/>
    <circle cx="48" cy="13" r="4.5" fill="#fff" fill-opacity="0.35"/>
    <path d="M24 46 L42 61 L24 76" fill="none" stroke="#F74C00" stroke-width="8" stroke-linecap="round" stroke-linejoin="round"/>
    <rect x="52" y="70" width="34" height="8" rx="4" fill="#8B5CF6"/>
  </g>
  <g transform="translate({word_dx:.2f} {word_dy:.2f})">
    <path fill="url(#word)" d="{path}"/>
  </g>
</svg>
"""
    out = Path(__file__).resolve().parent.parent / "docs" / "assets" / "logo.svg"
    out.write_text(svg)
    print(f"wrote {out} ({width:.0f}x{height:.0f}, wordmark {word_w:.0f}x{word_h:.0f})")


if __name__ == "__main__":
    main()
