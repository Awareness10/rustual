"""Generate the Unicode tables `rustual::validation` needs to behave exactly like Python.

    python3 scripts/validation_tables.py > crates/rustual/src/validation/tables.rs

Run with the Python whose behaviour Textual users get (the tables follow its `unicodedata`):

- `DECIMAL_ZEROS`: the `0` of every run of decimal digits (`float()` / `int()` accept any of them),
- `SPACES`: the characters `str.isspace()` accepts (`float()` / `int()` strip them),
- `NFKC_URL_DELIMITERS`: non-ASCII characters whose NFKC form contains one of `/?#@:`
  (`urllib.parse` rejects them in a netloc),
- `NON_PRINTABLE`: ranges `repr()` escapes (`not str.isprintable()`).
"""

import sys
import unicodedata


def main() -> None:
    zeros = [c for c in range(0x110000) if unicodedata.decimal(chr(c), None) == 0]
    # Every decimal digit belongs to a run of ten starting at one of the zeros.
    assert all(unicodedata.decimal(chr(z + i), None) == i for z in zeros for i in range(10))
    assert sum(unicodedata.decimal(chr(c), None) is not None for c in range(0x110000)) == 10 * len(zeros)

    spaces = [c for c in range(0x110000) if chr(c).isspace()]
    delimiters = [
        c for c in range(0x80, 0x110000) if any(d in unicodedata.normalize("NFKC", chr(c)) for d in "/?#@:")
    ]
    ranges = []
    start = None
    for c in range(0x110000):
        printable = chr(c).isprintable()
        if not printable and start is None:
            start = c
        elif printable and start is not None:
            ranges.append((start, c - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))

    out = sys.stdout
    out.write(
        "//! Unicode tables for Python-compatible parsing (generated by `scripts/validation_tables.py`\n"
        f"//! from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}). Do not edit.\n\n"
    )

    def table(name: str, doc: str, ty: str, items: list[str]) -> None:
        out.write(f"/// {doc}\npub(super) const {name}: &[{ty}] = &[\n")
        line = "   "
        for item in items:
            if len(line) + len(item) + 2 > 100:
                out.write(line.rstrip() + "\n")
                line = "   "
            line += f" {item},"
        out.write(line + "\n];\n\n")

    table("DECIMAL_ZEROS", "The `0` of each run of ten decimal digits (Python `unicodedata.decimal`).", "u32",
          [f"0x{c:04X}" for c in zeros])
    table("SPACES", "Characters Python's `str.isspace()` accepts.", "u32", [f"0x{c:04X}" for c in spaces])
    table("NFKC_URL_DELIMITERS", "Non-ASCII characters whose NFKC form contains one of `/?#@:`.", "u32",
          [f"0x{c:04X}" for c in delimiters])
    table("NON_PRINTABLE", "Inclusive ranges of characters that are not printable (`str.isprintable()`).",
          "(u32, u32)", [f"(0x{a:04X}, 0x{b:04X})" for a, b in ranges])


if __name__ == "__main__":
    main()
