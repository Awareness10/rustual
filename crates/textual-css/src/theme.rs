    /// Every variable of every builtin theme parses as the kind of value it is used for.
    #[test]
    fn all_variables_parse() {
        for theme in Theme::builtin() {
            for (k, v) in theme.to_variables() {
                let ok = if k.ends_with("text-style") || k.starts_with("link-style") {
                    parse_text_style(&v).is_ok()
                } else if k == "link-background" && v == "initial" {
                    true
                } else {
                    let mut s = Styles::new();
                    s.set_declaration("color", &v).is_ok()
                        && (v.starts_with("auto") || s.set_declaration("background", &v).is_ok())
                };
                assert!(ok, "theme {}: ${k}: {v:?} does not parse", theme.name);
            }
        }
    }
