    #[test]
    fn textual_dark_known_values() {
        let vars = Theme::by_name("textual-dark").unwrap().to_variables();
        assert_eq!(vars["primary"], "#0178D4");
        assert_eq!(vars["foreground"], "#E0E0E0");
        assert_eq!(vars["background"], "#121212");
        assert_eq!(vars["surface"], "#1E1E1E");
        assert_eq!(vars["text"], "auto 87%");
        assert_eq!(vars["text-muted"], "auto 60%");
        assert_eq!(vars["text-disabled"], "auto 38%");
        assert_eq!(vars["border"], "#0178D4");
        assert_eq!(vars["block-cursor-foreground"], "auto 87%");
        assert_eq!(vars["foreground-muted"], "#E0E0E099");
        assert_eq!(vars["boost"], "#FFFFFF0A");
        assert_eq!(vars["link-style-hover"], "bold not underline");
        // Shades are distinct and ordered by lightness.
        let l = |k: &str| Color::parse(&vars[k]).unwrap().brightness();
        assert!(l("primary-darken-3") < l("primary-darken-1"));
        assert!(l("primary-darken-1") < l("primary"));
        assert!(l("primary") < l("primary-lighten-1"));
        assert!(l("primary-lighten-1") < l("primary-lighten-3"));
    }

